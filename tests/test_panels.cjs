"use strict";

const assert = require("assert").strict;
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const context = {window: {}};
const source = fs.readFileSync(path.join(__dirname, "../src/expman/static/panels.js"), "utf8");
vm.runInNewContext(source, context);
const page = context.window.ExpmanPanels.page;
const preferences = context.window.ExpmanPanels.preferences;
assert.equal(preferences().panelSize, "medium");
assert.equal(preferences({panelSize: "large"}).panelSize, "large");
assert.equal(preferences({panelSize: "unknown"}).panelSize, "medium");
assert.deepEqual(Array.from(preferences({panels: ["a", "b"], options: {logY: true}}).logYPanels), ["a", "b"]);
assert.deepEqual(Array.from(preferences({panels: ["a"], options: {logY: true}, logYPanels: []}).logYPanels), []);
assert.deepEqual(Array.from(preferences({logYPanels: ["a", 1, "a", "b"]}).logYPanels), ["a", "b"]);
const savedLegend = preferences({overviewColors: {a: "#AB12cd", b: "red", c: "#123", d: 1}, hiddenOverviewCurves: ["a", "a", 1, "", "group:one"]});
assert.deepEqual(JSON.parse(JSON.stringify(savedLegend.overviewColors)), {a: "#ab12cd"});
assert.deepEqual(Array.from(savedLegend.hiddenOverviewCurves), ["a", "group:one"]);
assert.deepEqual(JSON.parse(JSON.stringify(preferences({overviewColors: ["#ffffff"], hiddenOverviewCurves: "a"}).overviewColors)), {});
assert.equal(preferences({hiddenOverviewCurves: "a"}).hiddenOverviewCurves.length, 0);
const colorIdentifiers = Array.from({length: 128}, (unused, index) => "experiment-" + index);
const defaultColors = context.window.ExpmanPanels.defaultColors(colorIdentifiers);
assert.equal(new Set(Object.values(defaultColors)).size, 128);
assert(Object.values(defaultColors).every(value => /^#[0-9a-f]{6}$/.test(value)));
const extendedColors = context.window.ExpmanPanels.defaultColors(colorIdentifiers, {custom: "#123456"});
assert.equal(extendedColors.custom, "#123456");
assert.equal(Object.keys(extendedColors).length, 129);
const elapsedText = context.window.ExpmanPanels.elapsedText;
assert.equal(elapsedText(86399), "23:59:59");
assert.equal(elapsedText(86400), "1d 00:00:00");
assert.equal(elapsedText(93784), "1d 02:03:04");
assert.equal(elapsedText(259200), "3d 00:00:00");
assert.equal(elapsedText(86399.6), "1d 00:00:00");
assert.equal(elapsedText(-93784), "-1d 02:03:04");
const tags = Array.from({length: 286}, (unused, index) => `metric/${index}`);
const original = tags.slice();
const visited = [];
for (let index = 0; index < page(tags).pages; index += 1) {
  const current = page(tags, "", index);
  assert(current.tags.length <= 32);
  visited.push(...current.tags);
}
assert.deepEqual(visited, tags);
assert.deepEqual(tags, original);
assert.equal(new Set(visited).size, 286);
assert.equal(page(tags, "", 999).page, 17);
assert.equal(page(tags, "", -3).page, 0);
assert.equal(page(tags, "", 0, 999).size, 32);
assert.equal(page(tags, "", 0, NaN).size, 16);
assert.equal(page([], "", 100).from, 0);
assert.equal(page([], "", 100).to, 0);
assert.equal(page([], "", 100).pages, 1);
assert.deepEqual(Array.from(page(["Train/Loss", "Train/Reward", "Eval/Loss"], " LOSS ").tags), ["Train/Loss", "Eval/Loss"]);
assert.equal(page(tags, "not-a-metric").total, 0);
assert.equal(page(tags, "metric/285", 18).page, 0);
assert.equal(page(tags, "metric/285", 18).from, 1);
assert.equal(page(tags, "metric/285", 18).to, 1);
console.log("Panel browsing: all 286 metrics reachable; filtering and request bounds verified");

const tree = context.window.ExpmanPanels.tree;
const nested = ["Train/loss/actor", "Train/loss/critic", "Train/reward", "Eval/reward", "steps", "Train/loss", "__proto__/value"];
const grouped = tree(nested);
assert.equal(grouped.total, nested.length);
assert.equal(grouped.root.groups.find(group => group.prefix === "Train").count, 4);
assert.equal(grouped.root.groups.find(group => group.prefix === "Train").groups[0].count, 2);
assert.deepEqual(Array.from(grouped.tags).sort(), nested.slice().sort());
assert.deepEqual(Array.from(tree(nested, "", ["Train/loss"]).tags).filter(tag => tag.startsWith("Train/")), ["Train/loss", "Train/reward"]);
assert(!tree(nested, "", ["Train"]).tags.some(tag => tag.startsWith("Train/")));
assert.equal(tree(nested, "CRITIC").total, 1);
assert.equal(tree(nested, "CRITIC", ["Train"]).tags.length, 0);
assert(tree(nested, "CRITIC", ["Train"]).prefixes.includes("Train/loss"));
assert.equal(tree(nested, "", grouped.prefixes).tags.length, 1);
assert.equal(tree(["/loss", "Train//loss"]).prefixes.length, 3);
const collapsed = tree(tags, "", ["metric"]);
assert.equal(collapsed.total, 286);
assert.equal(collapsed.tags.length, 0);
const expandedVisited = [];
for (let index = 0; index < page(grouped.tags, "", 0, 2).pages; index += 1) expandedVisited.push(...page(grouped.tags, "", index, 2).tags);
assert.deepEqual(expandedVisited.sort(), nested.slice().sort());
console.log("Panel groups: nested prefixes, collapse, matching counts, and paginated coverage verified");
const outlierRange = context.window.ExpmanPanels.outlierRange;
const plotted = [{y: Array.from({length: 100}, (unused, index) => index).concat(1e9)}];
const originalY = plotted[0].y.slice();
assert.deepEqual(Array.from(outlierRange(plotted)), [.5, 99.5]);
assert.deepEqual(plotted[0].y, originalY);
assert.equal(outlierRange([{y: [null, NaN, Infinity, -1, 0]}], true), null);
assert.deepEqual(Array.from(outlierRange([{y: [1, 1, 1]}])), [.95, 1.05]);
assert.deepEqual(Array.from(outlierRange([{y: [0, 0, 0]}])), [-1, 1]);
assert(outlierRange([{y: [1, 100]}])[1] > 100);
assert.deepEqual(Array.from(outlierRange(plotted.concat({y: [1e20], visible: "legendonly"}))), [.5, 99.5]);
const logValues = Array.from({length: 100}, (unused, index) => 10 ** (index / 10)).concat(1e100, 0, -1);
const logRange = outlierRange([{y: logValues}], true);
assert(Math.abs(logRange[0] - .05) < 1e-10);
assert(Math.abs(logRange[1] - 9.95) < 1e-10);
console.log("Outlier scaling: central 90%, log axes, finite values, hidden traces, constant ranges, and preserved observations verified");

"use strict";

const assert = require("assert").strict;
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const context = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../src/expman/static/combined.js"), "utf8"), context);
const combined = context.window.ExpmanCombined;
const scale = (values, mode) => Array.from(combined.scale(values, mode));
assert.deepEqual(scale([-300, 0, 900], "minmax"), [0, .25, 1]);
assert.deepEqual(scale([.001, .002, .005], "minmax"), [0, .25, 1]);
assert.deepEqual(scale([7, 7, 7], "minmax"), [.5, .5, .5]);
assert.deepEqual(scale([7, 7, 7], "standard"), [0, 0, 0]);
assert.deepEqual(scale([null, NaN, Infinity], "minmax"), [null, null, null]);
assert.deepEqual(scale([-4, null, 4], "standard"), [-1, null, 1]);
assert.deepEqual(scale([-1000, 0, 1000], "raw"), [-1000, 0, 1000]);
const standardized = scale([1e10 + 1, 1e10 + 2, 1e10 + 3], "standard");
assert(Math.abs(standardized.reduce((sum, value) => sum + value, 0)) < 1e-12);
assert(Math.abs(standardized.reduce((sum, value) => sum + value * value, 0) / 3 - 1) < 1e-12);
assert.equal(combined.preferences(null), null);
assert.equal(combined.preferences({experiment: "run", tags: []}), null);
const restored = combined.preferences({experiment: "run", tags: ["loss", "loss", 2, "reward"], scale: "invalid", smoothing: 8}, .7);
assert.deepEqual(JSON.parse(JSON.stringify(restored)), {experiment: "run", tags: ["loss", "reward"], offsets: {minmax: {}, standard: {}, raw: {}}, scaleWindow: null, scale: "minmax", smoothing: .7});
assert.equal(combined.preferences({experiment: "run", tags: Array.from({length: 100}, (unused, index) => String(index))}).tags.length, 32);
const offsets = combined.preferences({experiment: "run", tags: ["loss"], offsets: {raw: {loss: 15, absent: 20}, minmax: {loss: .2}, standard: {loss: Infinity}}});
assert.deepEqual(JSON.parse(JSON.stringify(offsets.offsets)), {raw: {loss: 15}, minmax: {loss: .2}, standard: {}});
const curve = {x: [0, 10, 20], y: [0, 100, 0]};
const range = (traces, bounds) => { const value = combined.visibleYRange(traces, bounds); return value == null ? value : Array.from(value); };
assert.deepEqual(range([curve], [8, 12]), [79, 101]);
assert.deepEqual(range([curve], [18, 12]), [17, 83]);
assert.deepEqual(range([curve, {x: [0, 20], y: [1e9, 1e9], visible: "legendonly"}], [8, 12]), [79, 101]);
assert.deepEqual(range([{x: [0, 20], y: [.5, .5]}], [8, 12]), [.475, .525]);
assert.equal(range([curve], [30, 40]), null);
assert.equal(range([{x: [0, 10, 20], y: [0, null, 100]}], [8, 12]), null);
assert.equal(range([curve], [NaN, 20]), null);
assert.equal(combined.valueAt(curve, 8), 80);
assert.equal(combined.valueAt(curve, -1), null);
const dated = {x: ["2026-01-01T00:00:00Z", "2026-01-01T00:00:10Z"], y: [0, 10]};
const origin = Date.parse(dated.x[0]);
assert.deepEqual(Array.from(combined.visibleYRange([dated], [origin + 2000, origin + 8000], Date.parse)), [1.7, 8.3]);
const fitted = combined.windowValues(curve, [8, 12]);
assert.deepEqual(Array.from(fitted), [100, 80, 80]);
assert.deepEqual(scale([-4, 1, -4], "raw"), [-4, 1, -4]);
assert.deepEqual(Array.from(combined.scale(curve.y, "minmax", fitted)), [-4, 1, -4]);
const larger = {x: [0, 10, 20], y: [1000, 10000, 1000]};
assert.deepEqual(Array.from(combined.scale(larger.y, "minmax", combined.windowValues(larger, [8, 12]))), [-4, 1, -4]);
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../src/expman/static/views.js"), "utf8"), context);
const signature = context.window.ExpmanViews.signature;
assert.equal(signature({selectionMode: "filters", selected: ["a"], filters: ["rule"]}), signature({filters: ["rule"], selected: ["a", "new"], selectionMode: "filters", namedView: "saved"}));
assert.notEqual(signature({selectionMode: "manual", selected: ["a"]}), signature({selectionMode: "manual", selected: ["a", "b"]}));
assert.notEqual(signature({selectionMode: "filters", filters: ["a"]}), signature({selectionMode: "filters", filters: ["b"]}));
assert.equal(signature({showAllPanels: true, panels: ["a"]}), signature({showAllPanels: true, panels: ["a", "new"]}));
console.log("Combined metrics: independent scales, constant and missing values, original units, stable standard scores, and bounded saved preferences verified");
